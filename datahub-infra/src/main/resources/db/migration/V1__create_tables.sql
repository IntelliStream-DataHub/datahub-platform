-- Label
CREATE TABLE label
(
    id              int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hash            bigint NOT NULL,
    name            varchar(512) NOT NULL,
    description     text NULL,
    i18n_code       text NULL,
    color           varchar(7) NOT NULL, --HTML color
    date_created    timestamp WITH TIME ZONE,
    last_updated    timestamp WITH TIME ZONE,
    CONSTRAINT label_hash_key UNIQUE (hash)
);

-- DataSet
CREATE TABLE data_set
(
    id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id         int NULL,
    external_id       varchar(256) NOT NULL,
    hash              bigint NOT NULL,
    deactivated       boolean not null DEFAULT FALSE,
    write_protected   boolean not null DEFAULT FALSE,
    name              varchar(512) NOT NULL,
    description       text NULL,
    date_created      timestamp WITH TIME ZONE,
    last_updated      timestamp WITH TIME ZONE,
    CONSTRAINT data_set_hash_key UNIQUE (hash),
    CONSTRAINT data_set_parent_id_fk
        FOREIGN KEY(parent_id)
            REFERENCES data_set(id)
);
-- Btree is better for exact matches and pattern matching at the beginning of strings
CREATE INDEX data_set_external_id_idx ON data_set USING btree (external_id);
CREATE INDEX data_set_name_idx ON data_set USING GIN (to_tsvector('simple', name));
-- DataSet Metadata
CREATE TABLE dataset_metadata
(
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id          int NOT NULL,
    key                 varchar(1024) NOT NULL,
    value               text NULL,
    CONSTRAINT dataset_metadata_dataset_id_fk
        FOREIGN KEY(dataset_id)
            REFERENCES data_set(id)
);
CREATE INDEX dataset_metadata_dataset_id_key_value_idx ON dataset_metadata USING btree (dataset_id, key, value);

