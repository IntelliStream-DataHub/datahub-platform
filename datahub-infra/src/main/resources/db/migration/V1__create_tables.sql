CREATE TABLE node
(
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                varchar(512) NOT NULL,
    description         text NULL,
    external_id         varchar(256) NOT NULL,
    external_id_hash    bigint NOT NULL,
    asset_id            bigint NULL,
    timeseries_id       bigint NULL,
    function_id         bigint NULL,
    labels              text NULL,
    data_set_id         int NULL,
    date_created        timestamp WITH TIME ZONE,
    last_updated        timestamp WITH TIME ZONE,
    is_root             bool NOT NULL DEFAULT false,
    node_type_id        int,
    CONSTRAINT node_external_id_hash_key UNIQUE (external_id_hash),
    CONSTRAINT node_node_type_id_fk
        FOREIGN KEY(node_type_id)
            REFERENCES node_type(id),
    CONSTRAINT node_asset_id_fk
        FOREIGN KEY(asset_id)
            REFERENCES asset(id),
    CONSTRAINT node_timeseries_id_fk
        FOREIGN KEY(timeseries_id)
            REFERENCES timeseries(id),
    CONSTRAINT node_function_id_fk
        FOREIGN KEY(function_id)
            REFERENCES function_entity(id)
);
CREATE INDEX node_name_idx ON node USING GIN (to_tsvector('simple', name));
CREATE INDEX node_id_node_type_id_idx ON node USING BTREE (id, node_type_id);
