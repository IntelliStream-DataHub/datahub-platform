-- The tables of intellistream-flow (datahub-flow): flows and their immutable versions. A flow's
-- deployment and schedule are columns on the flow, since a flow has exactly one of each. See
-- INTELLISTREAM_FLOW_PLAN.md, Appendix A and B.
--
-- In public, with the rest of the tenant's tables. Runs are not kept here: while they are queued,
-- running or just finished they are in the tenant's KVRocks, and once they have ended in its
-- ClickHouse (flow_run); see datahub-flow's RUN_STORE.md. Nothing here references another table:
-- a flow names its dataset by id and external id, and calls datahub-api for everything else.

CREATE TABLE flow (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id           text NOT NULL UNIQUE,

    -- The dataset that decides who sees the flow. The id is resolved from the definition's
    -- external id when the flow is saved and is what lists filter on (against GET /me/datasets);
    -- the external id is kept for display and for a flow whose dataset has since been deleted.
    data_set_id           bigint NOT NULL,
    data_set_external_id  text NOT NULL,

    name                  text NOT NULL,

    -- The latest saved version. Checked against flow_version by a deferred key (below), since a
    -- flow and its first version are inserted in one transaction.
    current_version       int NOT NULL CHECK (current_version >= 1),

    -- The deployment: the version that is switched on, its trigger, its limits and the identity
    -- its runs act as. Null until the flow is first deployed; re-deploying overwrites it, and the
    -- next run created uses it. The service tells the run store a deployment and its limits.
    deployed_version      int,
    enabled               boolean NOT NULL DEFAULT false,
    -- Why the service switched it off, when it was not a person: DATASET_DELETED.
    disabled_reason       text,
    -- The definition's trigger as deployed: manual or schedule, with cron, timezone, window and
    -- delay.
    trigger               jsonb,
    -- Execution limits.
    max_concurrent_runs   int NOT NULL DEFAULT 1 CHECK (max_concurrent_runs >= 1),
    max_attempts          int NOT NULL DEFAULT 2 CHECK (max_attempts >= 1),
    run_timeout           interval NOT NULL DEFAULT interval '15 minutes'
                              CHECK (run_timeout > interval '0'),
    -- Whose access runs use. 'deployer': the person who deployed it (identity_subject), through
    -- an offline token stored in Vault as flow.token.<id> in the tenant's tenant-config secret,
    -- never here. 'client': a registered client, by its name in the tenant's flow settings.
    identity_kind         text CHECK (identity_kind IN ('deployer', 'client')),
    identity_subject      text,
    identity_client_name  text,
    identity_state        text NOT NULL DEFAULT 'ok'
                              CHECK (identity_state IN ('ok', 'needs-reauthorisation')),
    identity_state_reason text,
    deployed_by           text,
    deployed_at           timestamp WITH TIME ZONE,

    -- The schedule, for a deployment with a schedule trigger: where it had got to. The run store is
    -- the authority and checkpoints it here, so a run store that lost it starts again from here
    -- rather than from the deployment, and the Runs overview reads it. next_tick is T (the run
    -- covers [T - window, T)); next_due_at is T + delay; last_tick is the last tick a run was
    -- created for, where catch-up after downtime starts.
    next_tick             timestamp WITH TIME ZONE,
    next_due_at           timestamp WITH TIME ZONE,
    last_tick             timestamp WITH TIME ZONE,

    created_by            text NOT NULL,
    created_at            timestamp WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_by            text NOT NULL,
    updated_at            timestamp WITH TIME ZONE NOT NULL DEFAULT now(),

    CHECK (deployed_version IS NULL OR (trigger IS NOT NULL AND identity_kind IS NOT NULL)),
    CHECK (identity_kind IS DISTINCT FROM 'deployer'
           OR (identity_subject IS NOT NULL AND identity_client_name IS NULL)),
    CHECK (identity_kind IS DISTINCT FROM 'client'
           OR (identity_client_name IS NOT NULL AND identity_subject IS NULL)),
    CHECK ((next_tick IS NULL) = (next_due_at IS NULL)),
    CHECK (next_due_at IS NULL OR next_due_at >= next_tick)
);

CREATE INDEX flow_data_set_idx ON flow (data_set_id);
-- The sweep: enabled schedules that are due.
CREATE INDEX flow_due_idx ON flow (next_due_at) WHERE enabled AND next_due_at IS NOT NULL;

-- A version never changes once saved: runs and failure events point at it, and an instance
-- caches its compiled form for as long as it lives. The trigger makes that a property of the
-- table rather than a convention of the service.
CREATE TABLE flow_version (
    flow_id    bigint NOT NULL REFERENCES flow (id) ON DELETE CASCADE,
    version    int NOT NULL CHECK (version >= 1),
    definition jsonb NOT NULL,
    created_by text NOT NULL,
    created_at timestamp WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (flow_id, version)
);

CREATE FUNCTION flow_forbid_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% rows are immutable', TG_TABLE_NAME;
END
$$;

CREATE TRIGGER flow_version_immutable BEFORE UPDATE ON flow_version
    FOR EACH ROW EXECUTE FUNCTION flow_forbid_update();

ALTER TABLE flow ADD CONSTRAINT flow_current_version_fk
    FOREIGN KEY (id, current_version) REFERENCES flow_version (flow_id, version)
    DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE flow ADD CONSTRAINT flow_deployed_version_fk
    FOREIGN KEY (id, deployed_version) REFERENCES flow_version (flow_id, version)
    DEFERRABLE INITIALLY DEFERRED;
