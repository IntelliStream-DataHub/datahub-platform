-- The tables of intellistream-flow (datahub-flow): flows, their immutable versions, and their
-- runs. A flow's deployment and schedule are columns on the flow, since a flow has exactly one of
-- each. See INTELLISTREAM_FLOW_PLAN.md, Appendix A and B.
--
-- In a schema of their own, and the first migration to create one. Every object is
-- schema-qualified rather than reached through search_path: connections go through pgbouncer in
-- transaction mode, which drops a search_path set on the connection. Flyway's own history table
-- stays where it is, in public. Nothing here references a table outside the schema: a flow names
-- its dataset by id and external id, and calls datahub-api for everything else.
CREATE SCHEMA IF NOT EXISTS flow;

CREATE TABLE flow.flow (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id           text NOT NULL UNIQUE,

    -- The dataset that decides who sees the flow. The id is resolved from the definition's
    -- external id when the flow is saved and is what lists filter on (against GET /me/datasets);
    -- the external id is kept for display and for a flow whose dataset has since been deleted.
    data_set_id           bigint NOT NULL,
    data_set_external_id  text NOT NULL,

    name                  text NOT NULL,

    -- The latest saved version. Checked against flow_version by a deferred key (below), since a
    -- flow and its first version are inserted in one transaction.
    current_version       int NOT NULL CHECK (current_version >= 1),

    -- The deployment: the version that is switched on, its trigger, its limits and the identity
    -- its runs act as. Null until the flow is first deployed; re-deploying overwrites it, and the
    -- next run created uses it. The claim locks this row while it counts running runs against
    -- max_concurrent_runs.
    deployed_version      int,
    enabled               boolean NOT NULL DEFAULT false,
    -- Why the service switched it off, when it was not a person: DATASET_DELETED.
    disabled_reason       text,
    -- The definition's trigger as deployed: manual or schedule, with cron, timezone, window and
    -- delay.
    trigger               jsonb,
    -- Execution limits, as columns because the claim reads them in SQL.
    max_concurrent_runs   int NOT NULL DEFAULT 1 CHECK (max_concurrent_runs >= 1),
    max_attempts          int NOT NULL DEFAULT 2 CHECK (max_attempts >= 1),
    run_timeout           interval NOT NULL DEFAULT interval '15 minutes'
                              CHECK (run_timeout > interval '0'),
    memory_bytes          bigint NOT NULL DEFAULT 536870912 CHECK (memory_bytes > 0),
    -- Whose access runs use. 'deployer': the person who deployed it (identity_subject), through
    -- an offline token stored in Vault as flow.token.<id> in the tenant's tenant-config secret,
    -- never here. 'client': a registered client, by its name in the tenant's flow settings.
    identity_kind         text CHECK (identity_kind IN ('deployer', 'client')),
    identity_subject      text,
    identity_client_name  text,
    identity_state        text NOT NULL DEFAULT 'ok'
                              CHECK (identity_state IN ('ok', 'needs-reauthorisation')),
    identity_state_reason text,
    deployed_by           text,
    deployed_at           timestamp WITH TIME ZONE,

    -- The schedule, for a deployment with a schedule trigger. The sweep locks due rows
    -- (FOR UPDATE SKIP LOCKED), creates the run for each tick and moves these forward in the same
    -- transaction: the schedule advances when a run is created, never when one finishes.
    -- next_tick is T (the run covers [T - window, T)); next_due_at is T + delay; last_tick is the
    -- last tick a run was created for, where catch-up after downtime starts.
    next_tick             timestamp WITH TIME ZONE,
    next_due_at           timestamp WITH TIME ZONE,
    last_tick             timestamp WITH TIME ZONE,

    created_by            text NOT NULL,
    created_at            timestamp WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_by            text NOT NULL,
    updated_at            timestamp WITH TIME ZONE NOT NULL DEFAULT now(),

    CHECK (deployed_version IS NULL OR (trigger IS NOT NULL AND identity_kind IS NOT NULL)),
    CHECK (identity_kind IS DISTINCT FROM 'deployer'
           OR (identity_subject IS NOT NULL AND identity_client_name IS NULL)),
    CHECK (identity_kind IS DISTINCT FROM 'client'
           OR (identity_client_name IS NOT NULL AND identity_subject IS NULL)),
    CHECK ((next_tick IS NULL) = (next_due_at IS NULL)),
    CHECK (next_due_at IS NULL OR next_due_at >= next_tick)
);

CREATE INDEX flow_data_set_idx ON flow.flow (data_set_id);
-- The sweep: enabled schedules that are due.
CREATE INDEX flow_due_idx ON flow.flow (next_due_at) WHERE enabled AND next_due_at IS NOT NULL;

-- A version never changes once saved: runs and failure events point at it, and an instance
-- caches its compiled form for as long as it lives. The trigger makes that a property of the
-- table rather than a convention of the service.
CREATE TABLE flow.flow_version (
    flow_id    bigint NOT NULL REFERENCES flow.flow (id) ON DELETE CASCADE,
    version    int NOT NULL CHECK (version >= 1),
    definition jsonb NOT NULL,
    created_by text NOT NULL,
    created_at timestamp WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (flow_id, version)
);

CREATE FUNCTION flow.forbid_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% rows are immutable', TG_TABLE_NAME;
END
$$;

CREATE TRIGGER flow_version_immutable BEFORE UPDATE ON flow.flow_version
    FOR EACH ROW EXECUTE FUNCTION flow.forbid_update();

ALTER TABLE flow.flow ADD CONSTRAINT flow_current_version_fk
    FOREIGN KEY (id, current_version) REFERENCES flow.flow_version (flow_id, version)
    DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE flow.flow ADD CONSTRAINT flow_deployed_version_fk
    FOREIGN KEY (id, deployed_version) REFERENCES flow.flow_version (flow_id, version)
    DEFERRABLE INITIALLY DEFERRED;

-- One execution of a flow, and the unit the instances claim, lease and retry. A preview is a run
-- too, and may run a definition that was never saved: then it has no flow version and carries
-- the definition itself.
CREATE TABLE flow.run (
    id                  uuid PRIMARY KEY,
    flow_id             bigint REFERENCES flow.flow (id) ON DELETE CASCADE,
    version             int,
    definition          jsonb,

    status              text NOT NULL
                            CHECK (status IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED', 'CANCELLED')),
    attempt             int NOT NULL DEFAULT 1 CHECK (attempt >= 1),
    max_attempts        int NOT NULL CHECK (max_attempts >= 1),
    -- Retry back-off: a pending run is not claimed before this.
    not_before          timestamp WITH TIME ZONE NOT NULL DEFAULT now(),
    cancel_requested    boolean NOT NULL DEFAULT false,
    preview             boolean NOT NULL DEFAULT false,
    -- Failed after its last attempt, and datahub-api could not take the run-failed event yet:
    -- the next sweep writes it.
    failure_event_owed  boolean NOT NULL DEFAULT false,

    memory_bytes        bigint NOT NULL CHECK (memory_bytes > 0),
    run_timeout         interval NOT NULL CHECK (run_timeout > interval '0'),

    -- The lease. Renewed every 15 s by one statement per tenant per instance, so it must stay a
    -- HOT update: there is deliberately no index on lease_expires_at.
    owner               text,
    lease_expires_at    timestamp WITH TIME ZONE,

    -- What input the run covers. Always a window [window_start, window_end) in the first
    -- version; a listener batch's boundaries later.
    window_start        timestamp WITH TIME ZONE,
    window_end          timestamp WITH TIME ZONE,
    input_boundaries    jsonb,

    -- What it ran with: every parameter as resolved (a secret by name, never its value), and the
    -- version of every processor in the flow.
    parameters          jsonb NOT NULL DEFAULT '{}',
    processor_versions  jsonb NOT NULL DEFAULT '{}',

    trigger             text NOT NULL CHECK (trigger IN ('schedule', 'manual', 'rerun', 'preview')),
    triggered_by        text,
    -- Whose access the run used: the deployer's subject or the registered client's name.
    run_as              text,

    created_at          timestamp WITH TIME ZONE NOT NULL DEFAULT now(),
    started_at          timestamp WITH TIME ZONE,
    finished_at         timestamp WITH TIME ZONE,
    error_code          text,
    error               text,
    stats               jsonb,

    FOREIGN KEY (flow_id, version) REFERENCES flow.flow_version (flow_id, version),
    CHECK ((flow_id IS NOT NULL AND version IS NOT NULL)
           OR (preview AND definition IS NOT NULL)),
    CHECK ((window_start IS NULL) = (window_end IS NULL)),
    CHECK (window_start IS NULL OR window_start < window_end),
    CONSTRAINT run_running_has_lease
        CHECK (status <> 'RUNNING' OR (owner IS NOT NULL AND lease_expires_at IS NOT NULL))
);

-- The claim: pending runs, earliest window first. Created-at breaks ties between runs of the
-- same window and orders runs without one.
CREATE INDEX run_pending_idx ON flow.run (window_start, created_at) WHERE status = 'PENDING';
-- The reaper reads every running run and filters expired leases in memory.
CREATE INDEX run_running_idx ON flow.run (status) WHERE status = 'RUNNING';
-- Failure events datahub-api could not take yet.
CREATE INDEX run_failure_event_owed_idx ON flow.run (id) WHERE failure_event_owed;
-- A flow's runs, newest first.
CREATE INDEX run_flow_created_idx ON flow.run (flow_id, created_at DESC);

-- Run rows are updated several times each and deleted by retention, so vacuum them more eagerly
-- than the default 20 % of the table, and leave room on each page for heartbeats to stay HOT.
ALTER TABLE flow.run SET (
    fillfactor = 80,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_analyze_scale_factor = 0.05
);
